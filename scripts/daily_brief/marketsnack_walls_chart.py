"""Render the SPX walls chart — MarketSnack (solid) vs the engine ±5% (dashed), ALWAYS both.

Norman wants to ALWAYS see BOTH columns (2026-10-23): MarketSnack (his primary source, captured
MANUALLY via Edge — see [[use-marketsnack-for-analysis]]) and the options engine (±5% max-OI, live
from Polygon). MarketSnack needs a logged-in browser the headless brief can't reach, so the
MarketSnack levels below are captured by hand and this chart is NOT auto-generated by the brief;
regenerate it with a fresh capture, and the brief embeds it only while fresh (<=10h) else omits it,
never showing stale/half data. See [[reliability-money-at-stake]].
"""

from __future__ import annotations

import datetime
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))
OUT = REPO / "output"

# ── MarketSnack SPX levels — captured MANUALLY. UPDATE spot/asof/rows on every refresh. ──────────
SPOT = 7624.0
ASOF = "cierre 23-Oct"
# (label, expiration ISO, put_wall, magnet, call_wall) — from MarketSnack "Price Pressure" per expiry
ROWS: list[tuple[str, str, float, float, float]] = [
    ("Oct 23", "2026-10-23", 7620, 7625, 7875),
    ("Oct 30", "2026-10-30", 7500, 7650, 7900),
    ("Nov 06", "2026-11-06", 6800, 7750, 7850),
    ("Nov 13", "2026-11-13", 6400, 7700, 7850),
    ("Nov 20", "2026-11-20", 7500, 8000, 7900),
]


def engine_walls(iso_dates: list[str], band_pct: float = 5.0):
    """Engine (±band max-OI) PW/Mag/CW per expiration date, LIVE from Polygon. Returns
    ({iso: (pw, mag, cw)}, spot). Empty on failure so the chart still draws the MarketSnack side."""
    try:
        from dotenv import load_dotenv
        load_dotenv(REPO / ".env")
        from drift_sentiment import polygon_client as pc, walls
        from drift_sentiment.magneto import magneto
        spot, contracts = pc.fetch_near_term("SPX", max_dte=40)
    except Exception:  # noqa: BLE001
        return {}, None
    by_exp: dict = defaultdict(list)
    for c in contracts:
        by_exp[c.expiration].append(c)
    out: dict = {}
    for iso in iso_dates:
        try:
            d = datetime.date.fromisoformat(iso)
        except Exception:  # noqa: BLE001
            continue
        cs = by_exp.get(d, [])
        if not (cs and spot):
            continue
        band = [c for c in cs if abs(c.strike - spot) / spot * 100 <= band_pct]
        cw = walls.call_wall(band)
        pw = walls.put_wall(band)
        mg = magneto(band)
        out[iso] = (pw.strike if pw else None, mg[0] if mg else None, cw.strike if cw else None)
    return out, spot


def _dte(iso: str) -> int:
    return (datetime.date.fromisoformat(iso) - datetime.date.today()).days


def build(out: Path | None = None) -> Path | None:
    """Save output/spx_walls_marketsnack.png — MarketSnack (solid) vs engine ±5% (dashed)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    if len(ROWS) < 2:
        return None
    eng, _ = engine_walls([r[1] for r in ROWS])
    x = list(range(len(ROWS)))
    fig = plt.figure(figsize=(11, 6.6), facecolor="#0b0f17")
    ax = fig.add_subplot(111)
    ax.set_facecolor("#0b0f17")
    for sp in ax.spines.values():
        sp.set_color("#2a3442")
    ax.tick_params(colors="#9aa7b5", labelsize=10)
    ax.grid(True, color="#161d27", lw=0.5)
    ax.axhline(SPOT, color="#4dd0e1", ls=":", lw=1.2, alpha=0.85)
    ax.text(len(x) - 0.9, SPOT, f"  Spot {SPOT:,.0f}", color="#4dd0e1", fontsize=9, va="center",
            fontweight="bold", family="monospace")

    emap = {2: 0, 3: 1, 4: 2}  # row-tuple index -> engine-tuple index
    metrics = [(2, "#ef5350", "Put Wall"), (3, "#cfd8e3", "Magneto"), (4, "#1fae7e", "Call Wall")]
    for idx, col, _name in metrics:
        ax.plot(x, [r[idx] for r in ROWS], "-o", color=col, lw=2.6, ms=8,
                markeredgecolor="#0b0f17", markeredgewidth=1.2, zorder=3)
        en = [(eng.get(r[1]) or (None, None, None))[emap[idx]] for r in ROWS]
        ex = [xi for xi, v in zip(x, en) if v is not None]
        ey = [v for v in en if v is not None]
        if ey:
            ax.plot(ex, ey, "--s", color=col, lw=2.0, ms=7, markerfacecolor="#0b0f17",
                    markeredgecolor=col, markeredgewidth=1.8, alpha=0.9, zorder=2)

    leg1 = [Line2D([0], [0], color=c, lw=3, label=n) for _, c, n in metrics]
    leg2 = [Line2D([0], [0], color="#e8eaed", lw=2.6, ls="-", marker="o", label="MarketSnack"),
            Line2D([0], [0], color="#e8eaed", lw=2.0, ls="--", marker="s",
                   markerfacecolor="#0b0f17", label="Motor ±5%")]
    ax.add_artist(ax.legend(handles=leg1, loc="upper left", facecolor="#141b26",
                            edgecolor="#2a3442", labelcolor="#e8eaed", fontsize=9, framealpha=0.9))
    ax.legend(handles=leg2, loc="lower left", facecolor="#141b26", edgecolor="#2a3442",
              labelcolor="#e8eaed", fontsize=9, framealpha=0.9)

    ax.set_xticks(x)
    ax.set_xticklabels([f"{r[0]}\n({_dte(r[1])}d)" for r in ROWS], color="#cfd8e3", fontsize=10)
    ax.set_xlim(-0.35, len(x) - 0.55)
    ax.set_ylabel("Precio (SPX)", color="#9aa7b5", fontsize=10)
    ax.set_title(f"SPX muros: MarketSnack (sólido) vs Motor ±5% (punteado)  ·  {ASOF}  ·  educativo",
                 color="#e8eaed", fontsize=12.5, fontweight="bold")
    OUT.mkdir(exist_ok=True)
    png = out or (OUT / "spx_walls_marketsnack.png")
    fig.savefig(png, dpi=150, facecolor="#0b0f17", bbox_inches="tight")
    plt.close(fig)
    return png


def table_html() -> str:
    """HTML fragment: MarketSnack vs engine ±5%, both columns per expiration (cell = MS / Motor)."""
    eng, _ = engine_walls([r[1] for r in ROWS])
    th = ("padding:4px 8px;border:1px solid #2a3442;background:#141b26;color:#e8eaed;"
          "font:700 11px monospace;text-align:right")
    td = "padding:4px 8px;border:1px solid #2a3442;color:#cfd8e3;font:11px monospace;text-align:right"

    def cell(ms, en):
        return f"{int(ms):,} / " + ("n/d" if en is None else f"{int(en):,}")

    body = ""
    for lbl, iso, pw, mg, cw in ROWS:
        e = eng.get(iso) or (None, None, None)
        body += (f"<tr><td style='{td};text-align:left'>{lbl} ({_dte(iso)}d)</td>"
                 f"<td style='{td}'>{cell(pw, e[0])}</td><td style='{td}'>{cell(mg, e[1])}</td>"
                 f"<td style='{td}'>{cell(cw, e[2])}</td></tr>")
    head = "".join(f"<th style='{th}'>{h}</th>" for h in
                   ("Venc.", "Put Wall MS/Motor", "Magneto MS/Motor", "Call Wall MS/Motor"))
    return (f"<table style='border-collapse:collapse;margin:6px 0'><thead><tr>{head}</tr>"
            f"</thead><tbody>{body}</tbody></table>")


if __name__ == "__main__":
    p = build()
